#!/usr/bin/env python3
"""Generate RealisticWorld_BP/scripts/weather/biomeClimate.js from Mojang's
official biome definitions (minecraft:climate temperature and downfall).

Usage:
  git clone --depth 1 --filter=blob:none --sparse https://github.com/Mojang/bedrock-samples.git
  (cd bedrock-samples && git sparse-checkout set behavior_pack/biomes version.json)
  python3 scripts/gen_biome_climate.py path/to/bedrock-samples
"""

import glob
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "RealisticWorld_BP" / "scripts" / "weather" / "biomeClimate.js"

# Biomes where open water dominates: smaller day/night swing, more fog.
WATER_WORDS = ("ocean", "river", "swamp", "beach", "mangrove", "stone_beach")


def strip_comments(text):
    return re.sub(r"^\s*//.*$", "", text, flags=re.M)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    samples = Path(sys.argv[1])
    version = json.loads((samples / "version.json").read_text())["latest"]["version"]
    rows = []
    for f in sorted(glob.glob(str(samples / "behavior_pack" / "biomes" / "*.json"))):
        biome = json.loads(strip_comments(Path(f).read_text()))["minecraft:biome"]
        ident = biome["description"]["identifier"]
        climate = biome["components"].get("minecraft:climate")
        if not climate:
            continue
        water = 1 if any(w in ident for w in WATER_WORDS) else 0
        rows.append((ident, float(climate.get("temperature", 0.5)), float(climate.get("downfall", 0.5)), water))

    lines = [
        "// GENERATED by scripts/gen_biome_climate.py - do not edit by hand.",
        f"// Source: Mojang/bedrock-samples {version}, behavior_pack/biomes/*.json (minecraft:climate).",
        "// [vanilla temperature, vanilla downfall, water-dominated 0/1]",
        "",
        "/** @type {Readonly<Record<string, readonly [number, number, number]>>} */",
        "export const BIOME_CLIMATE = Object.freeze({",
    ]
    for ident, t, d, w in rows:
        lines.append(f'  "{ident}": [{t}, {d}, {w}],')
    lines += ["});", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {len(rows)} biomes to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
