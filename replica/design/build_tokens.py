#!/usr/bin/env python3
"""tokens.json + tokens.dark.json -> tokens.css and tailwind.tokens.js.
Run after every token change (and after /replica-brand): python3 build_tokens.py"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
light = json.load(open(os.path.join(here, "tokens.json")))
dark = json.load(open(os.path.join(here, "tokens.dark.json")))

def block(colors):
    return "\n".join(f"  --color-{k}: {v};" for k, v in colors.items())

css = ["/* Generated by build_tokens.py from tokens.json. Do not edit by hand. */",
       ":root {", block(light["color"])]
css += [f"  --font-sans: {light['font']['sans']};", f"  --font-mono: {light['font']['mono']};"]
for k, v in light["radius"].items(): css.append(f"  --radius-{k}: {v}px;")
for k, v in light["shadow"].items(): css.append(f"  --shadow-{k}: {v};")
for k, v in light["motion"].items(): css.append(f"  --motion-{k}: {v};")
css += ["}", "", "@media (prefers-color-scheme: dark) {", "  :root:not([data-theme='light']) {",
        "  " + block(dark["color"]).replace("\n", "\n  "), "  }", "}", "",
        ":root[data-theme='dark'], [data-theme='dark'] {", block(dark["color"]), "}", "",
        "[data-theme='light'] {", block(light["color"]), "}", ""]
open(os.path.join(here, "tokens.css"), "w").write("\n".join(css))

tw = {
  "colors": {k: f"var(--color-{k})" for k in light["color"]},
  "fontFamily": {"sans": ["var(--font-sans)"], "mono": ["var(--font-mono)"]},
  "fontSize": {k: [f"{v['size']}px", {"lineHeight": f"{v['line']}px", "fontWeight": str(v["weight"])}]
               for k, v in light["type"].items() if not k.startswith("_")},
  "spacing": {str(i): f"{v}px" for i, v in enumerate(light["space"])},
  "borderRadius": {k: f"var(--radius-{k})" for k in light["radius"]},
  "boxShadow": {k: f"var(--shadow-{k})" for k in light["shadow"]},
}
open(os.path.join(here, "tailwind.tokens.js"), "w").write(
  "// Generated by build_tokens.py. Use in tailwind.config.js (web) and NativeWind v4 (mobile):\n"
  "//   theme: { extend: require('./replica/design/tailwind.tokens.js') }\n"
  "// Components use role classes (bg-surface, text-muted), never raw hex.\n"
  "module.exports = " + json.dumps(tw, indent=2) + ";\n")
print("wrote tokens.css, tailwind.tokens.js")
